  c.beginPath();
  c.moveTo(15, 59);
  c.lineTo(55, 59);
  c.stroke();

  shape("M77 68 Q69 61 72 57 Q80 55 83 67 Z", "#64836b", 2);
  shape("M79 69 Q65 61 59 77 Q52 92 66 99 Q78 107 93 98 Q107 89 99 76 Q93 62 79 69 Z", "#de8b44", 2.5);
