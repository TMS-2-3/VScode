import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const sourceRoot = resolve(projectRoot, "src");
const outputPath = resolve(projectRoot, "dist/game.js");
const modules = new Map();
const visiting = new Set();

function moduleId(path) {
  const id = relative(sourceRoot, path);
  if (id.startsWith(`..${sep}`) || id === ".." || id.startsWith(sep)) {
    throw new Error(`Import outside src is not supported: ${path}`);
  }
  return id.replaceAll(sep, "/");
}

function collect(path) {
  if (modules.has(path)) return;
  if (visiting.has(path)) throw new Error(`Circular import: ${path}`);
  visiting.add(path);

  let source = readFileSync(path, "utf8").replaceAll("\r\n", "\n");
  const imports = [];
  const exports = new Set();

  source = source.replace(
    /^import\s*\{([^}]+)\}\s*from\s*["']([^"']+)["'];?[ \t]*\n?/gm,
    (_statement, names, specifier) => {
      if (!specifier.startsWith(".")) {
        throw new Error(`Only relative imports are supported: ${specifier}`);
      }
      const dependency = resolve(dirname(path), specifier);
      const bindings = names.split(",").map((name) => name.trim()).filter(Boolean);
      imports.push({ dependency, bindings });
      return "";
    },
  );

  source = source.replace(
    /^export\s+\{([^}]+)\};?[ \t]*\n?/gm,
    (_statement, names) => {
      for (const name of names.split(",").map((part) => part.trim()).filter(Boolean)) {
        if (!/^[A-Za-z_$][\w$]*$/.test(name)) {
          throw new Error(`Unsupported export in ${path}: ${name}`);
        }
        exports.add(name);
      }
      return "";
    },
  );
  source = source.replace(
    /^export\s+(const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm,
    (_statement, kind, name) => {
      exports.add(name);
      return `${kind} ${name}`;
    },
  );

  if (/^(?:import|export)\b/m.test(source)) {
    throw new Error(`Unsupported module syntax in ${path}`);
  }

  for (const entry of imports) {
    moduleId(entry.dependency);
    collect(entry.dependency);
    for (const binding of entry.bindings) {
      const importedName = binding.split(/\s+as\s+/)[0];
      if (!modules.get(entry.dependency).exports.has(importedName)) {
        throw new Error(`${moduleId(entry.dependency)} does not export ${importedName}`);
      }
    }
  }

  source = source.replaceAll(
    "import.meta.url",
    `new URL(${JSON.stringify(`../src/${moduleId(path)}`)}, __bundleUrl).href`,
  );
  modules.set(path, { source, imports, exports });
  visiting.delete(path);
}

collect(resolve(sourceRoot, "main.js"));

const sections = [
  "// Generated by node scripts/build-file-version.mjs. Edit src/ instead.",
  '"use strict";',
  "(() => {",
  "  const __bundleUrl = document.currentScript.src;",
  "  const __modules = Object.create(null);",
];

for (const [path, module] of modules) {
  sections.push(`  // src/${moduleId(path)}`);
  sections.push(`  __modules[${JSON.stringify(moduleId(path))}] = (() => {`);
  for (const { dependency, bindings } of module.imports) {
    const names = bindings.map((name) => name.replace(/\s+as\s+/, ": ")).join(", ");
    sections.push(`    const { ${names} } = __modules[${JSON.stringify(moduleId(dependency))}];`);
  }
  sections.push(module.source);
  sections.push(`    return { ${[...module.exports].join(", ")} };`);
  sections.push("  })();");
}

sections.push("})();", "");
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, sections.join("\n"), "utf8");
console.log(`Built ${relative(projectRoot, outputPath)} from ${modules.size} modules.`);
